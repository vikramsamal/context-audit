def test_large_data_file_rule():
    # Small json -> not flagged as large data
    small_info = FileInfo(
        path="/project/config.json",
        relative_path="config.json",
        extension=".json",
        size_bytes=2000,
        char_count=2000,
        line_count=50,
        estimated_tokens=500,
    )
    assert not any(m.category == ContextCategory.LARGE_DATA for m in evaluate_rules(small_info))

    # Large json (>50KB) -> flagged
    large_info = FileInfo(
        path="/project/dataset.json",
        relative_path="dataset.json",
        extension=".json",
        size_bytes=60 * 1024,
        char_count=60 * 1024,
        line_count=2000,
        estimated_tokens=15000,
    )
    assert any(m.category == ContextCategory.LARGE_DATA for m in evaluate_rules(large_info))


