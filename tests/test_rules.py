def test_lockfile_rule():
    lockfiles = ["package-lock.json", "poetry.lock", "Cargo.lock", "pnpm-lock.yaml", "go.sum"]
    for lockfile_name in lockfiles:
        info = FileInfo(
            path=f"/project/{lockfile_name}",
            relative_path=lockfile_name,
            extension=f".{lockfile_name.split('.')[-1]}",
            size_bytes=15000,
            char_count=15000,
            line_count=400,
            estimated_tokens=3750,
        )
        matches = evaluate_rules(info)
        assert any(m.category == ContextCategory.LOCKFILE for m in matches), (
            f"Failed for {lockfile_name}"
        )


