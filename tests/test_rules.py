"""Tests for deterministic rule evaluation."""

from __future__ import annotations

from context_audit.models import ContextCategory, FileInfo
from context_audit.rules import evaluate_rules


def test_clean_source_file_not_unnecessary():
    info = FileInfo(
        path="/project/src/main.py",
        relative_path="src/main.py",
        extension=".py",
        size_bytes=1000,
        char_count=1000,
        line_count=40,
        estimated_tokens=250,
    )
    matches = evaluate_rules(info, "def main():\n    print('hello')\n")
    assert len(matches) == 0
    assert not any(m.is_unnecessary for m in matches)


